// TestMoveGenerationFuzzAgainstStockfish validates our move generation against Stockfish
func TestMoveGenerationFuzzAgainstStockfish(t *testing.T) {
	if testing.Short() {
		t.Skip("Skipping Stockfish fuzz test in short mode")
	}
	
	// Path to Stockfish binary
	stockfishPath, err := filepath.Abs("../stockfish/stockfish-ubuntu-x86-64-avx2")
	if err != nil {
		t.Fatalf("Failed to get stockfish path: %v", err)
	}
	
	// Create Stockfish client
	sf, err := NewStockfishClient(stockfishPath)
	if err != nil {
		t.Fatalf("Failed to create Stockfish client: %v", err)
	}
	defer sf.Close()
	
	// Test positions covering various scenarios
	testPositions := []struct {
		name string
		fen  string
	}{
		{"Starting Position", "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1"},
		{"After e4", "rnbqkbnr/pppppppp/8/8/4P3/8/PPPP1PPP/RNBQKBNR b KQkq e3 0 1"},
		{"After e4 e5", "rnbqkbnr/pppp1ppp/8/4p3/4P3/8/PPPP1PPP/RNBQKBNR w KQkq e6 0 2"},
		{"Sicilian Defense", "rnbqkbnr/pp1ppppp/8/2p5/4P3/8/PPPP1PPP/RNBQKBNR w KQkq c6 0 2"},
		{"King's Gambit", "rnbqkbnr/pppp1ppp/8/4p3/4PP2/8/PPPP2PP/RNBQKBNR b KQkq f3 0 2"},
		{"Castling Available", "r1bqk1nr/pppp1ppp/2n5/2b1p3/2B1P3/5N2/PPPP1PPP/RNBQK2R w KQkq - 4 4"},
		{"Endgame", "8/8/8/8/8/8/4P3/4K2k w - - 0 1"},
		{"Pawn Promotion", "8/P7/8/8/8/8/8/4K2k w - - 0 1"},
		{"En Passant", "rnbqkbnr/ppp2ppp/8/3Pp3/8/8/PPP1PPPP/RNBQKBNR w KQkq e6 0 3"},
		{"Complex Middle Game", "r1bq1rk1/ppp2ppp/2n2n2/2bpp3/2B1P3/3P1N2/PPP2PPP/RNBQ1RK1 w - - 0 8"},
	}
	
	for _, testPos := range testPositions {
		t.Run(testPos.name, func(t *testing.T) {
			// Parse position with our engine
			pos, err := ParseFEN(testPos.fen)
			if err != nil {
				t.Fatalf("Failed to parse FEN %s: %v", testPos.fen, err)
			}
			
			// Get moves from our engine
			ourMoves := GenerateLegalMoves(pos)
			ourMoveStrings := make([]string, len(ourMoves))
			for i, move := range ourMoves {
				ourMoveStrings[i] = moveToUCIString(move)
			}
			sort.Strings(ourMoveStrings)
			
			// Get moves from Stockfish
			stockfishMoves, err := sf.GetLegalMoves(testPos.fen)
			if err != nil {
				t.Fatalf("Failed to get Stockfish moves for %s: %v", testPos.name, err)
			}
			
			// Compare move sets
			t.Logf("Position: %s", testPos.name)
			t.Logf("FEN: %s", testPos.fen)
			t.Logf("Our moves (%d): %v", len(ourMoveStrings), ourMoveStrings)
			t.Logf("Stockfish moves (%d): %v", len(stockfishMoves), stockfishMoves)
			
			// Check for illegal moves generated by our engine
			illegalMoves := make([]string, 0)
			for _, ourMove := range ourMoveStrings {
				found := false
				for _, sfMove := range stockfishMoves {
					if ourMove == sfMove {
						found = true
						break
					}
				}
				if !found {
					illegalMoves = append(illegalMoves, ourMove)
				}
			}
			
			// Check for legal moves missed by our engine
			missedMoves := make([]string, 0)
			for _, sfMove := range stockfishMoves {
				found := false
				for _, ourMove := range ourMoveStrings {
					if sfMove == ourMove {
						found = true
						break
					}
				}
				if !found {
					missedMoves = append(missedMoves, sfMove)
				}
			}
			
			// Report results
			if len(illegalMoves) > 0 {
				t.Errorf("🚨 ILLEGAL MOVES generated by our engine: %v", illegalMoves)
			}
			
			if len(missedMoves) > 0 {
				t.Logf("⚠️  Legal moves missed by our engine (not critical): %v", missedMoves)
				// This is a warning, not an error, as missing legal moves is less critical than generating illegal ones
			}
			
			if len(illegalMoves) == 0 && len(missedMoves) == 0 {
				t.Logf("✅ Perfect match with Stockfish!")
			}
		})
	}
}

// TestRandomPositionsFuzz generates random positions and validates against Stockfish
func TestRandomPositionsFuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("Skipping random fuzz test in short mode")
	}
	
	// Path to Stockfish binary
	stockfishPath, err := filepath.Abs("../stockfish/stockfish-ubuntu-x86-64-avx2")
	if err != nil {
		t.Fatalf("Failed to get stockfish path: %v", err)
	}
	
	// Create Stockfish client
	sf, err := NewStockfishClient(stockfishPath)
	if err != nil {
		t.Fatalf("Failed to create Stockfish client: %v", err)
	}
	defer sf.Close()
	
	// Generate random positions by playing random games
	numTests := 10 // Keep it reasonable for CI
	
	for i := 0; i < numTests; i++ {
		t.Run(fmt.Sprintf("RandomGame_%d", i), func(t *testing.T) {
			// Start from starting position and play random moves
			pos, _ := ParseFEN("rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1")
			
			// Play 5-15 random moves to get interesting positions
			numMoves := 5 + (i % 10)
			
			for move := 0; move < numMoves; move++ {
				legalMoves := GenerateLegalMoves(pos)
				if len(legalMoves) == 0 {
					break // Game ended
				}
				
				// Pick a random legal move
				randomMove := legalMoves[move%len(legalMoves)]
				
				// Make the move
				_, _, _, _ = pos.MakeMove(randomMove)
			}
			
			// Now test this random position
			currentFEN := GenerateFEN(pos)
			
			// Get moves from our engine
			ourMoves := GenerateLegalMoves(pos)
			ourMoveStrings := make([]string, len(ourMoves))
			for j, move := range ourMoves {
				ourMoveStrings[j] = moveToUCIString(move)
			}
			sort.Strings(ourMoveStrings)
			
			// Get moves from Stockfish
			stockfishMoves, err := sf.GetLegalMoves(currentFEN)
			if err != nil {
				t.Logf("Skipping position due to Stockfish error: %v", err)
				return
			}
			
			// Check for illegal moves
			illegalMoves := make([]string, 0)
			for _, ourMove := range ourMoveStrings {
				found := false
				for _, sfMove := range stockfishMoves {
					if ourMove == sfMove {
						found = true
						break
					}
				}
				if !found {
					illegalMoves = append(illegalMoves, ourMove)
				}
			}
			
			if len(illegalMoves) > 0 {
				t.Errorf("🚨 ILLEGAL MOVES in random position %d: %v", i, illegalMoves)
				t.Errorf("Position FEN: %s", currentFEN)
				t.Errorf("Our moves: %v", ourMoveStrings)
				t.Errorf("Stockfish moves: %v", stockfishMoves)
			}
		})
	}
}

// moveToUCIString converts our Move to UCI string format (e.g., "e2e4", "e7e8q")
func moveToUCIString(move Move) string {
	uci := move.Source().String() + move.Destination().String()
	
	// Add promotion piece if applicable
	if move.PromoType() != NoType {
		switch move.PromoType() {
		case Queen:
			uci += "q"
		case Rook:
			uci += "r"
		case Bishop:
			uci += "b"
		case Knight:
			uci += "n"
		}
	}
	
	return uci
}

