// moveToUCIString converts our Move to UCI string format (e.g., "e2e4", "e7e8q")
func moveToUCIString(move Move) string {
	uci := move.Source().String() + move.Destination().String()
	
	// Add promotion piece if applicable
	if move.PromoType() != NoType {
		switch move.PromoType() {
		case Queen:
			uci += "q"
		case Rook:
			uci += "r"
		case Bishop:
			uci += "b"
		case Knight:
			uci += "n"
		}
	}
	
	return uci
}

